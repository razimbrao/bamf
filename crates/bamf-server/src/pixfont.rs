/// Rows of `c`, or `None` for a space or a character the font lacks
/// (drawn blank).
pub fn glyph(c: char) -> Option<&'static [&'static str; 7]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| rows)
}

/// Width of `text` in font pixels.
pub fn width(text: &str) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 {
        0
    } else {
        n * (WIDTH + SPACING) - SPACING
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_5x7() {
        for (c, rows) in GLYPHS {
            assert!(
                rows.iter().all(|r| r.len() == WIDTH as usize),
                "glyph {c:?} has a row of the wrong width"
            );
        }
    }

    #[test]
    fn lower_case_maps_to_upper() {
        assert_eq!(glyph('a'), glyph('A'));
        assert!(glyph(' ').is_none());
        assert!(glyph('×').is_some());
    }

    #[test]
    fn width_counts_spacing() {
        assert_eq!(width(""), 0);
        assert_eq!(width("A"), 5);
        assert_eq!(width("AB"), 11);
    }
}
